#!/usr/bin/env bash
# restart.sh - clean up pipeline outputs to force a fresh (re)run.
#
# Usage:
#   ./restart.sh --only-backbone   Remove every file/log that is backbone-dependent, i.e.
#                                   whose Snakemake rule declares an output containing one of
#                                   the binning wildcards {window_mode}/{window_size}/{step}
#                                   (GC content, distances, overlaps, epigenomes,
#                                   haploinsufficiency, ohnologs/paralogs, per-bin
#                                   RepliSeq/ATAC-seq/Hi-C outputs, the combined feature
#                                   matrix, and the log/ directory of every such rule).
#                                   The set of rules/paths is derived by parsing
#                                   workflow/rules/**/*.smk at run time (see
#                                   find_backbone_targets.py) - it is not a hand-maintained
#                                   list, so it can't silently drift out of sync with the
#                                   pipeline. Preserves fastq/bam/sra/pairs and every other
#                                   sample/assembly-level artifact that does NOT depend on
#                                   window_mode/window_size/step (expensive to regenerate).
#                                   Shows a "would remove" preview and asks for confirmation
#                                   before deleting anything.
#
#   ./restart.sh --hard             Remove EVERYTHING generated by the pipeline (resources/,
#                                   data/, results/, logs/, .snakemake/ - fastq/bam/sra
#                                   included), except the "starting" files - raw, manually-
#                                   provided/downloaded source data that has no producing rule
#                                   and therefore cannot be regenerated by Snakemake itself.
#
# Neither option touches config/ or the workflow/ directory itself.

set -euo pipefail

REPO_ROOT="$(pwd)"
cd "$REPO_ROOT"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FINDER="$SCRIPT_DIR/find_backbone_targets.py"

# ---------------------------------------------------------------------------
# Files with NO producing rule - manually downloaded/curated, cannot be
# regenerated by the pipeline. Only relevant to --hard (backed up, then
# restored after the wipe). Verify these paths match your actual files before
# running --hard - the COSMIC/GDC entries in particular used placeholder names
# during testing and may not match your real downloads' exact filenames.
# ---------------------------------------------------------------------------
#
# IMPORTANT: entries must point at the exact raw file (or, when the raw data is a whole
# untouched download, its own uniquely-named subfolder) - NEVER at a shared parent directory
# that some rule *also* writes derived output into. Several of these directories are mixed
# (raw file + rule-produced files side by side): DepMap/{models,probabilities,scores} and
# COSMIC/{classification,samples} all have a rule that writes its filtered/derived output as
# a sibling of the raw file in the very same directory (confirmed by reading
# filter_CRISPR_models.smk, filter_CRISPR_probabilities.smk, filter_CRISPR_scores.smk,
# filter_classification_COSMIC.smk, filter_samples_COSMIC.smk, get_bin_level_essentiality.smk
# - see also config/config_dataset.yaml for the exact raw filenames used below). Protecting
# the whole parent directory there would silently preserve stale derived files across a
# --hard reset, and made --only-backbone skip a real, removable backbone-dependent file
# during testing. resources/IntOGen and resources/GDC/CNAs/files are NOT mixed this way
# (their derived outputs live in separate sibling directories - processed/, aggregated/,
# ampl/, del/, checks/ - verified by reading process_IntOGen.smk and the GDC_CNA/*.smk
# rules), so protecting them at directory level is safe.
STARTING_FILES=(
    "resources/fragile_sites/origin/fragile_sites_li_hg38.bed"
    "resources/ohnologs_and_paralogs/origin/OhnologList.RData"
    "resources/ohnologs_and_paralogs/origin/ParalogList.RData"
    "resources/haploinsufficiency/haploinsufficiency.csv"
    "resources/epigenomes/mapping_EID_tt_raw.tsv"
    "resources/DepMap/models/Model.csv"
    "resources/DepMap/probabilities/CRISPRGeneDependency.csv"
    "resources/DepMap/scores/CRISPRGeneEffect.csv"
    "resources/IntOGen/IntOGen-Drivers-20240920"
    # NOTE (verify before --hard): COSMIC/GDC paths below used placeholder names during
    # testing - check these match your real downloaded files' actual names before relying on
    # --hard to preserve them.
    "resources/COSMIC/classification/Cosmic_Classification_Tsv_v103_GRCh38"
    "resources/COSMIC/samples/Cosmic_Sample_Tsv_v103_GRCh38"
    "resources/COSMIC/mutations/coding/Cosmic_GenomeScreensMutant_Tsv_v103_GRCh38"
    "resources/COSMIC/mutations/noncoding/Cosmic_NonCodingVariants_Tsv_v103_GRCh38"
    "resources/GDC/CNAs/clinical.cohort.2026-01-28"
    "resources/GDC/CNAs/gdc_sample_sheet.2026-01-28.tsv"
    "resources/GDC/CNAs/gdc_manifest.2026-01-28.170055.txt"
    "resources/GDC/CNAs/files"
)

usage() {
    echo "Usage: $0 --only-backbone | --hard"
    exit 1
}

# Return 0 (true) if candidate path $1 IS, or lies strictly inside, one of the
# STARTING_FILES entries. Used as a defensive guard on top of the glob-based
# targeting - belt and braces, since this is a destructive script.
is_protected_starting_file() {
    local candidate="$1"
    local f
    for f in "${STARTING_FILES[@]}"; do
        if [ "$candidate" == "$f" ] || [[ "$candidate" == "$f"/* ]]; then
            return 0
        fi
    done
    return 1
}

[ $# -eq 1 ] || usage

case "$1" in

    --only-backbone)
        echo "[$(date)] Computing backbone-dependent targets from workflow/rules/**/*.smk ..."

        if [ -d "workflow/rules" ]; then
            RULES_ARGS=(workflow/rules)
        elif ls ./*.smk >/dev/null 2>&1; then
            echo "  (workflow/rules/ not found - falling back to *.smk in repo root)"
            RULES_ARGS=(. --flat)
        else
            echo "ERROR: no rule files found (looked for workflow/rules/**/*.smk and ./*.smk)." >&2
            exit 1
        fi

        if [ ! -f "$FINDER" ]; then
            echo "ERROR: helper script not found at $FINDER" >&2
            exit 1
        fi

        mapfile -t PARSED < <(python3 "$FINDER" "${RULES_ARGS[@]}")

        OUTPUT_GLOBS=()
        LOG_RULE_NAMES=()
        for line in "${PARSED[@]}"; do
            kind="${line%%$'\t'*}"
            value="${line#*$'\t'}"
            if [ "$kind" == "OUTPUT_GLOB" ]; then
                OUTPUT_GLOBS+=("$value")
            elif [ "$kind" == "LOG_DIR" ]; then
                LOG_RULE_NAMES+=("$value")
            fi
        done

        if [ ${#OUTPUT_GLOBS[@]} -eq 0 ] && [ ${#LOG_RULE_NAMES[@]} -eq 0 ]; then
            echo "No backbone-dependent rules found - nothing to do. Aborting without changes."
            exit 0
        fi

        # --- Expand output globs against the real filesystem ---
        shopt -s nullglob
        TARGETS=()
        for pattern in "${OUTPUT_GLOBS[@]}"; do
            for match in $pattern; do
                if is_protected_starting_file "$match"; then
                    echo "  WARNING: '$match' matched pattern '$pattern' but is a protected" \
                         "starting file - skipping it. This should not normally happen;" \
                         "please double-check STARTING_FILES and the rule that produced" \
                         "this glob." >&2
                    continue
                fi
                TARGETS+=("$match")
            done
        done

        # --- Add log directories for every backbone-dependent rule ---
        for rule in "${LOG_RULE_NAMES[@]}"; do
            logdir="logs/$rule"
            if [ -e "$logdir" ]; then
                TARGETS+=("$logdir")
            fi
        done
        shopt -u nullglob

        # De-duplicate and sort for a stable, readable preview. Guard against an empty
        # array: `printf '%s\n'` with zero arguments still prints one blank line (the
        # format string is reused at least once), which would otherwise turn into one
        # bogus empty-string "target" - confirmed by an idempotency test run.
        if [ ${#TARGETS[@]} -gt 0 ]; then
            mapfile -t TARGETS < <(printf '%s\n' "${TARGETS[@]}" | sort -u)
        fi

        if [ ${#TARGETS[@]} -eq 0 ]; then
            echo "[$(date)] Computed the backbone-dependent rule set, but no matching files" \
                 "exist on disk yet. Nothing to remove."
            exit 0
        fi

        echo
        echo "The following ${#TARGETS[@]} path(s) would be removed (--only-backbone):"
        printf '  would remove: %s\n' "${TARGETS[@]}"
        echo
        read -r -p "Type 'yes' to proceed: " confirm
        [ "$confirm" == "yes" ] || { echo "Aborted. Nothing was removed."; exit 1; }

        echo "[$(date)] Removing ${#TARGETS[@]} path(s)..."
        for t in "${TARGETS[@]}"; do
            rm -rf -- "$t"
        done

        echo "[$(date)] Done. Verifying fastq/bam/sra/pairs are still present:"
        find resources -maxdepth 3 \( -iname "fastq" -o -iname "bam" -o -iname "sra" -o -iname "pairs" \) | sort
        ;;

    --hard)
        echo "[$(date)] HARD RESET - removing ALL generated resources/data/results/logs."
        echo "would remove: resources/ data/ results/ logs/ .snakemake/ (everything except the starting files below)"
        echo "Only the following 'starting' files (no producing rule) will be preserved:"
        printf '  %s\n' "${STARTING_FILES[@]}"
        read -r -p "Type 'yes' to proceed: " confirm
        [ "$confirm" == "yes" ] || { echo "Aborted."; exit 1; }

        BACKUP_DIR=$(mktemp -d)
        echo "[$(date)] Backing up starting files to $BACKUP_DIR..."
        for f in "${STARTING_FILES[@]}"; do
            if [ -e "$f" ]; then
                mkdir -p "$BACKUP_DIR/$(dirname "$f")"
                cp -r "$f" "$BACKUP_DIR/$f"
            else
                echo "  WARNING: '$f' not found - skipping (check STARTING_FILES if this is unexpected)"
            fi
        done

        echo "[$(date)] Wiping resources/ data/ results/ logs/ .snakemake/ ..."
        rm -rf resources data results logs .snakemake

        echo "[$(date)] Restoring starting files..."
        for f in "${STARTING_FILES[@]}"; do
            if [ -e "$BACKUP_DIR/$f" ]; then
                mkdir -p "$(dirname "$f")"
                cp -r "$BACKUP_DIR/$f" "$f"
            fi
        done
        rm -rf "$BACKUP_DIR"

        echo "[$(date)] Done. Remaining files under resources/:"
        find resources -maxdepth 3 -type f -o -type d | sort
        ;;

    *)
        usage
        ;;
esac